fn parse_dll_versions_file(file_path: &PathBuf) -> Result<HashMap<String, String>, Box<dyn std::error::Error>> {
    println!("[+] Reading DLL versions from: {}", file_path.display());
    
    let content = fs::read_to_string(file_path)?;
    
    let mut dll_map = HashMap::new();
    
    // Parse lines like: ("rasmans.dll", "10.0.14393.8688"),
    for line in content.lines() {
        let trimmed = line.trim();
        if trimmed.starts_with("(\"") && trimmed.contains("\",") {
            // Extract DLL name and version from: ("name.dll", "version"),
            if let Some(start) = trimmed.find("(\"") {
                if let Some(middle) = trimmed.find("\", \"") {
                    if let Some(end) = trimmed.rfind("\")") {
                        let dll_name = &trimmed[start+2..middle];
                        let version = &trimmed[middle+4..end];
                        dll_map.insert(dll_name.to_string(), version.to_string());
                    }
                }
            }
        }
    }
    
    if dll_map.is_empty() {
        return Err("No DLL entries found in file. Make sure it's in the correct format.".into());
    }
    
    println!("[+] Loaded {} DLL entries\n", dll_map.len());
    
    Ok(dll_map)
}

/// Winbindex DLL Downloader
/// Downloads Windows DLLs from winbindex.m417z.com based on version or KB
#[derive(Parser, Debug)]
#[command(author, version, about, long_about = None)]
struct Args {
    /// Path to the dll_versions.rs file generated by parse_cbs_dlls.py
    #[arg(short = 'f', long, default_value = "dll_versions.rs")]
    hashmap_file: PathBuf,
    
    #[command(subcommand)]
    command: Commands,
}

#[derive(Subcommand, Debug)]
enum Commands {
    /// Download DLLs matching specific versions from a HashMap
    Version {
        /// Output directory for downloaded DLLs
        #[arg(short, long, default_value = "./downloaded_dlls")]
        output: PathBuf,

        /// Architecture (x64, arm64, insider)
        #[arg(short, long, default_value = "x64")]
        arch: String,
    },
    /// Download DLLs from a specific KB update (uses same HashMap as version mode)
    Kb {
        /// KB number (e.g., KB5048685)
        #[arg(short, long)]
        kb: String,

        /// Output directory for downloaded DLLs
        #[arg(short, long, default_value = "./downloaded_dlls")]
        output: PathBuf,

        /// Architecture (x64, arm64, insider)
        #[arg(short, long, default_value = "x64")]
        arch: String,
    },
}

#[derive(Debug, Deserialize, Serialize)]
struct WinbindexFile {
    #[serde(rename = "windowsVersions")]
    windows_versions: HashMap<String, WindowsVersion>,
}

#[derive(Debug, Deserialize, Serialize)]
struct WindowsVersion {
    #[serde(rename = "updateInfo")]
    update_info: HashMap<String, UpdateInfo>,
}

#[derive(Debug, Deserialize, Serialize)]
struct UpdateInfo {
    #[serde(rename = "windowsVersions")]
    windows_versions: Vec<String>,
    
    #[serde(rename = "updateKb")]
    update_kb: Option<String>,
    
    #[serde(rename = "releaseDate")]
    release_date: Option<String>,
    
    #[serde(rename = "fileInfo")]
    file_info: FileInfo,
}

#[derive(Debug, Deserialize, Serialize)]
struct FileInfo {
    sha256: String,
    
    #[serde(rename = "virtualSize")]
    virtual_size: Option<u64>,
    
    version: Option<String>,
    
    #[serde(rename = "signingDate")]
    signing_date: Option<String>,
    
    #[serde(rename = "machineType")]
    machine_type: Option<u32>,
}

async fn fetch_winbindex_data(dll_name: &str, _arch: &str) -> Result<Value, Box<dyn std::error::Error>> {
    // Winbindex data is at: https://winbindex.m417z.com/data/by_filename_compressed/{filename}.json.gz
    // Architecture filtering happens INSIDE the JSON data, not via URL path
    // NOTE: Filenames are case-sensitive, usually lowercase
    
    let lowercase_name = dll_name.to_lowercase();
    let url_lowercase = format!("https://winbindex.m417z.com/data/by_filename_compressed/{}.json.gz", lowercase_name);
    
    println!("[+] Fetching data for {} from Winbindex...", dll_name);
    println!("    URL: {}", url_lowercase);
    
    let client = reqwest::Client::new();
    let mut response = client
        .get(&url_lowercase)
        .send()
        .await?;
    
    // If lowercase fails and it's different from original, try original case
    if !response.status().is_success() && lowercase_name != dll_name {
        let url_original = format!("https://winbindex.m417z.com/data/by_filename_compressed/{}.json.gz", dll_name);
        println!("    Trying original case: {}", url_original);
        
        response = client
            .get(&url_original)
            .send()
            .await?;
    }
    
    if !response.status().is_success() {
        if response.status().as_u16() == 404 {
            eprintln!("\n[!] {} is NOT indexed in Winbindex", dll_name);
            eprintln!("    Winbindex only indexes DLLs found in Windows Update packages.");
            eprintln!("    Skipping...");
        }
        return Err(format!("HTTP {}", response.status()).into());
    }
    
    let bytes = response.bytes().await?;
    
    // Decompress gzip data
    let mut decoder = flate2::read::GzDecoder::new(&bytes[..]);
    let mut decompressed = String::new();
    std::io::Read::read_to_string(&mut decoder, &mut decompressed)?;
    
    let data: Value = serde_json::from_str(&decompressed)?;
    Ok(data)
}

async fn download_file(dll_name: &str, file_info: &Value, output_path: &PathBuf) -> Result<(), Box<dyn std::error::Error>> {
    let expected_sha256 = file_info.get("sha256")
        .and_then(|v| v.as_str())
        .ok_or("Missing SHA256")?;
    
    let timestamp = file_info.get("timestamp")
        .and_then(|v| v.as_u64())
        .ok_or("Missing timestamp")?;
    
    let size = file_info.get("virtualSize")
        .or_else(|| file_info.get("size"))
        .and_then(|v| v.as_u64())
        .ok_or("Missing size")?;
    
    // Microsoft Symbol Server URL format:
    // https://msdl.microsoft.com/download/symbols/{filename}/{TIMESTAMP}{SIZE}/{filename}
    let url = format!(
        "https://msdl.microsoft.com/download/symbols/{}/{:X}{:X}/{}",
        dll_name,
        timestamp,
        size,
        dll_name
    );
    
    println!("[+] Downloading: {}", output_path.display());
    println!("    URL: {}", url);
    println!("    DEBUG: timestamp={:X} size={:X}", timestamp, size);
    
    let client = reqwest::Client::new();
    let response = client.get(&url).send().await?;
    
    if !response.status().is_success() {
        return Err(format!("Download failed: HTTP {}", response.status()).into());
    }
    
    let total_size = response.content_length().unwrap_or(0);
    let pb = ProgressBar::new(total_size);
    pb.set_style(
        ProgressStyle::default_bar()
            .template("{spinner:.green} [{elapsed_precise}] [{bar:40.cyan/blue}] {bytes}/{total_bytes} ({eta})")
            .unwrap()
            .progress_chars("#>-"),
    );
    
    let mut file = fs::File::create(output_path)?;
    let mut downloaded = 0u64;
    let mut hasher = Sha256::new();
    
    let bytes = response.bytes().await?;
    downloaded += bytes.len() as u64;
    pb.set_position(downloaded);
    
    hasher.update(&bytes);
    file.write_all(&bytes)?;
    
    pb.finish_with_message("Download complete");
    
    // Verify SHA256
    let result_hash = hex::encode(hasher.finalize());
    if result_hash.to_lowercase() == expected_sha256.to_lowercase() {
        println!("[✓] SHA256 verified: {}", result_hash);
    } else {
        println!("[!] SHA256 mismatch!");
        println!("    Expected: {}", expected_sha256);
        println!("    Got:      {}", result_hash);
        return Err("SHA256 verification failed".into());
    }
    
    Ok(())
}

fn find_version_match(data: &Value, target_version: &str, arch: &str) -> Option<(String, String, String, Value)> {
    // Returns: (sha256, version, update_kb, fileInfo)
    // New structure: top level is SHA256 hashes
    
    if let Some(obj) = data.as_object() {
        // Iterate through SHA256 hashes at top level
        for (sha256_key, sha_data) in obj.iter() {
            // Get fileInfo to check architecture and version
            if let Some(file_info) = sha_data.get("fileInfo") {
                // Check architecture via machineType
                let machine_type = file_info.get("machineType").and_then(|v| v.as_u64());
                let is_correct_arch = match (arch, machine_type) {
                    ("x64", Some(34404)) => true,  // 0x8664 = x64
                    ("arm64", Some(43620)) => true, // 0xAA64 = ARM64
                    ("insider", Some(34404)) => true, // Prefer x64 for insider
                    _ => false,
                };
                
                if !is_correct_arch {
                    continue;
                }
                
                // Check if version matches
                if let Some(version) = file_info.get("version").and_then(|v| v.as_str()) {
                    // Version format is like "10.0.26100.7309 (WinBuild.160101.0800)"
                    // Extract just the version number part
                    let version_num = version.split_whitespace().next().unwrap_or(version);
                    
                    if version_num == target_version || version == target_version {
                        // Found matching version! Now find a KB for it
                        let mut kb = "unknown".to_string();
                        
                        if let Some(windows_versions) = sha_data.get("windowsVersions").and_then(|v| v.as_object()) {
                            // Get the first KB we find (there may be multiple)
                            for (_win_ver, win_data) in windows_versions.iter() {
                                if let Some(kb_obj) = win_data.as_object() {
                                    if let Some((kb_name, _)) = kb_obj.iter().next() {
                                        kb = kb_name.clone();
                                        break;
                                    }
                                }
                            }
                        }
                        
                        return Some((sha256_key.clone(), version.to_string(), kb, file_info.clone()));
                    }
                }
            }
        }
    }
    
    None
}

fn find_kb_matches(data: &Value, target_kb: &str, arch: &str) -> Vec<(String, String, Value)> {
    // Returns: Vec<(sha256, version, fileInfo)>
    // New structure: top level is SHA256 hashes, KB is nested inside windowsVersions
    let mut results = Vec::new();
    
    if let Some(obj) = data.as_object() {
        // Iterate through SHA256 hashes at top level
        for (sha256_key, sha_data) in obj.iter() {
            // Get fileInfo to check architecture and get version
            if let Some(file_info) = sha_data.get("fileInfo") {
                // Check architecture via machineType
                let machine_type = file_info.get("machineType").and_then(|v| v.as_u64());
                let is_correct_arch = match (arch, machine_type) {
                    ("x64", Some(34404)) => true,  // 0x8664 = x64
                    ("arm64", Some(43620)) => true, // 0xAA64 = ARM64
                    ("insider", Some(34404)) => true, // Prefer x64 for insider
                    _ => false,
                };
                
                if !is_correct_arch {
                    continue;
                }
                
                let version = file_info.get("version")
                    .and_then(|v| v.as_str())
                    .unwrap_or("unknown")
                    .to_string();
                
                // Now check if this SHA256 entry contains the target KB
                if let Some(windows_versions) = sha_data.get("windowsVersions").and_then(|v| v.as_object()) {
                    for (_win_ver, win_data) in windows_versions.iter() {
                        if let Some(kb_obj) = win_data.as_object() {
                            for (kb_name, _kb_data) in kb_obj.iter() {
                                // Check if KB matches
                                if kb_name.to_lowercase() == target_kb.to_lowercase() || 
                                   format!("KB{}", kb_name).to_lowercase() == target_kb.to_lowercase() {
                                    // Found a match!
                                    results.push((sha256_key.clone(), version.clone(), file_info.clone()));
                                    break; // Don't add duplicates from same SHA256
                                }
                            }
                        }
                    }
                }
            }
        }
    }
    
    results
}

#[tokio::main]
async fn main() -> Result<(), Box<dyn std::error::Error>> {
    let args = Args::parse();
    
    // Parse the DLL versions HashMap from the file
    let dll_versions = parse_dll_versions_file(&args.hashmap_file)?;
    
    match args.command {
        Commands::Version { output, arch } => {
            println!("[+] Mode: Download by version");
            println!("[+] Will match exact versions from HashMap\n");
            
            fs::create_dir_all(&output)?;
            
            for (dll_name, target_version) in dll_versions.iter() {
                println!("[*] Processing: {} (target version: {})", dll_name, target_version);
                
                let data = match fetch_winbindex_data(dll_name, &arch).await {
                    Ok(d) => d,
                    Err(e) => {
                        eprintln!("[!] Skipping {}: {}\n", dll_name, e);
                        continue;
                    }
                };
                
                if let Some((sha256, version, kb, file_info)) = find_version_match(&data, target_version, &arch) {
                    println!("[✓] Found match!");
                    println!("    Version: {}", version);
                    println!("    KB: {}", kb);
                    println!("    SHA256: {}", sha256);
                    
                    let output_path = output.join(dll_name);
                    
                    match download_file(dll_name, &file_info, &output_path).await {
                        Ok(_) => println!("[✓] Successfully downloaded: {}\n", dll_name),
                        Err(e) => println!("[!] Failed to download {}: {}\n", dll_name, e),
                    }
                } else {
                    println!("[!] No match found for version: {}\n", target_version);
                }
            }
        }
        
        Commands::Kb { kb, output, arch } => {
            println!("[+] Mode: Download by KB");
            println!("[+] Target KB: {}", kb);
            println!("[+] Will download DLLs from HashMap for this KB (ignoring version check)\n");
            
            fs::create_dir_all(&output)?;
            
            for (dll_name, _target_version) in dll_versions.iter() {
                println!("[*] Processing: {} (KB: {})", dll_name, kb);
                
                let data = match fetch_winbindex_data(dll_name, &arch).await {
                    Ok(d) => d,
                    Err(e) => {
                        eprintln!("[!] Skipping {}: {}\n", dll_name, e);
                        continue;
                    }
                };
                
                let matches = find_kb_matches(&data, &kb, &arch);
                
                if matches.is_empty() {
                    println!("[!] No matches found for KB: {}\n", kb);
                    continue;
                }
                
                // Take the first match (usually there's only one per KB)
                let (sha256, version, file_info) = &matches[0];
                
                println!("[✓] Found match!");
                println!("    Version: {}", version);
                println!("    SHA256: {}", sha256);
                
                let output_path = output.join(dll_name);
                
                match download_file(dll_name, file_info, &output_path).await {
                    Ok(_) => println!("[✓] Successfully downloaded: {}\n", dll_name),
                    Err(e) => println!("[!] Failed to download {}: {}\n", dll_name, e),
                }
            }
        }
    }
    
    Ok(())
}
